"""P311 — the firmware-update safety gate.

The user's binding order: NO firmware update may ever break a panel again.
The P310 incident happened through a chain of removable weaknesses; every
link is pinned here. This file is the RELEASE GATE for every future firmware
release — it must pass before anything ships:

  1. bootloader rollback enabled (a bad OTA rolls back, never bricks)
  2. the OTA stall watchdog can never fire on a waiting display
  3. display restart actually takes the screen over (never stuck at splash)
  4. the panel can always be re-provisioned (the setup form saves)
  5. the panel can always be diagnosed (serial reset-reason + [app] mirror)
  6. the radio burst is capped (the RF power-up spike cannot trip a supply)
  7. the recovery set is generated by one script with integrity gates
  8. the wrong stock image can never ship again
  9. the bundled app's embedded version matches the release carriers
"""
from __future__ import annotations

import hashlib
import pathlib
import re

REPO = pathlib.Path(__file__).resolve().parent.parent
FW = REPO / "firmware-native" / "src"
RELEASES = REPO / "firmware" / "releases"
BUNDLED = REPO / "custom_components" / "nspanel_core" / "firmware"


def _read(path) -> str:
    return path.read_text(errors="replace")


# 1. rollback -----------------------------------------------------------------

def test_bootloader_rollback_is_enabled():
    cfg = _read(REPO / "firmware-native" / "sdkconfig.native_idf5")
    assert "CONFIG_BOOTLOADER_APP_ROLLBACK_ENABLE=y" in cfg, \
        "a failed OTA would have nothing to roll back to"
    # the confirm seatbelt must exist too
    assert "esp_ota_mark_app_valid_cancel_rollback" in \
        _read(REPO / "firmware-native" / "src" / "ota.cpp")


# 2. watchdog -----------------------------------------------------------------

def test_the_ota_watchdog_is_fed_on_every_display_wait():
    ota = _read(REPO / "firmware-native" / "src" / "ota.cpp")
    # P310: the TFT attempt loop feeds progress at the loop head — a silent
    # display can never reach the 120 s stall restart
    marker = 'nsp_display_send_command("DRAKJHSUYDGBNCJHGJKSHBDN");'
    assert "s_last_progress_us = esp_timer_get_time();" in \
        ota[ota.index("for (int attempt = 0; attempt < 3; attempt++)"):
            ota.index(marker)]


def test_watchdog_never_restarts_while_the_display_merely_sits_idle():
    ota = _read(REPO / "firmware-native" / "src" / "ota.cpp")
    # the watchdog only exists behind an explicit state != IDLE check
    assert ota.index("void nsp_ota_watchdog_feed_check") < \
        ota.index("esp_restart();", ota.index("void nsp_ota_watchdog_feed_check"))


# 3. display restart ----------------------------------------------------------

def test_display_restart_takes_the_screen_over():
    display = _read(REPO / "firmware-native" / "src" / "display.cpp")
    # after a successful handshake the screen must be navigated off the splash
    restart = display[display.index("bool nsp_display_restart"):]
    assert "nsp_display_after_handshake();" in restart


# 4. the setup form saves -----------------------------------------------------

def test_the_setup_form_submits_with_the_csrf_header():
    pages = _read(REPO / "firmware-native" / "src" / "webui_pages.cpp")
    # the native form could never send the header (the P310 403 dead-lock);
    # the form must submit via fetch with the required header
    setup = pages[pages.index("std::string nsp_web_setup_page"):]
    assert "fetch('/save'" in setup
    assert "'X-NSPanel':'1'" in setup or '"X-NSPanel"' in setup


# 5. diagnosability -----------------------------------------------------------

def test_the_panel_reports_its_own_reset_reason():
    main = _read(REPO / "firmware-native" / "src" / "main.cpp")
    assert "esp_reset_reason()" in main
    assert "[app] boot:" in main


def test_every_app_log_line_reaches_the_serial_console():
    mqtt = _read(REPO / "firmware-native" / "src" / "mqtt.cpp")
    assert 'printf("[app] %s\\n", msg);' in mqtt


# 6. the radio burst ----------------------------------------------------------

def test_the_radio_tx_power_is_capped():
    wifi = _read(REPO / "firmware-native" / "src" / "wifi.cpp")
    assert "esp_wifi_set_max_tx_power" in wifi


# 7. the recovery set is generated, with integrity gates ----------------------

def test_the_recovery_script_exists_and_gates_its_output():
    script = _read(REPO / "scripts" / "make_recovery_set.py")
    for gate in ('bootloader[0] == 0xE9', 'partitions[0:2] == b"\\xaa\\x50"',
                 'app[0] == 0xE9', 'all(b == 0xFF for b in otadata)'):
        assert gate in script, gate


def test_the_recovery_image_is_present_and_intact():
    merged = RELEASES / "recovery-merged-flash-0.1.13.bin"
    if not merged.is_file():
        import pytest
        pytest.skip("recovery image not generated yet")
    m = merged.read_bytes()
    assert m[0x1000] == 0xE9
    assert m[0x8000:0x8002] == b"\xaa\x50"
    assert m[0x10000] == 0xE9
    # the bundled app and the merged image must be THE SAME BUILD
    app = m[0x10000:0x10000 + len((BUNDLED / "sonoff" / "firmware.bin").read_bytes())]
    assert app == (BUNDLED / "sonoff" / "firmware.bin").read_bytes()


# 8. the wrong stock image can never ship again -------------------------------

def test_no_stock_or_foreign_merged_image_exists_anywhere():
    for path in (REPO / "firmware" / "merged-flash.bin",
                 BUNDLED / "sonoff" / "merged_flash.bin",
                 BUNDLED / "custom" / "merged_flash.bin"):
        assert not path.exists(), f"the wrong stock image {path} is back"


# 9. the carriers agree, byte-deep -------------------------------------------

def test_the_bundled_app_carries_the_release_version():
    version = (BUNDLED / "version").read_text().strip()
    manifest = __import__("json").loads(
        (REPO / "firmware" / "manifest.json").read_text())
    assert manifest["version"] == version, "manifest/firmware version drift"
    app = (BUNDLED / "sonoff" / "firmware.bin").read_bytes()
    desc = app[0x20:0x120]
    # the embedded app descriptor must carry exactly this version
    assert version.encode() in desc, \
        f"the bundled binary reports a different version than {version}"
    assert hashlib.md5(app).hexdigest() == (
        manifest["files"]["firmware/sonoff/firmware.bin"]["md5"]
        if isinstance(manifest["files"]["firmware/sonoff/firmware.bin"], dict)
        else manifest["files"]["firmware/sonoff/firmware.bin"]), "bundled md5 drift"
